// node passwords.test.js -- cek brankas: enkripsi, master salah, data diubah, ganti password, CSV Apple
const assert = require('assert'), fs = require('fs'), os = require('os'), path = require('path')
const { createVault, generate, parseCsv, toCsv } = require('./passwords')
const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'almac-vault-')), 'passwords.vault')
const v = createVault(file)
v.setup('correct horse')
v.data.entries.push({ id: 'e1', origin: 'https://github.com', username: 'ali', password: 's3cr3t,"x"' })
v.save()
assert(!fs.readFileSync(file, 'utf8').includes('s3cr3t') && !fs.readFileSync(file, 'utf8').includes('github'), 'plaintext leaked to disk')
v.lock()
assert.equal(v.unlock('wrong'), false)
assert.equal(v.unlock('correct horse'), true)
assert.equal(v.data.entries[0].password, 's3cr3t,"x"')
const k = v.key(); v.lock(); assert(v.unlockWithKey(k))
assert(v.changePassword('correct horse', 'new pass')); v.lock()
assert(!v.unlock('correct horse') && v.unlock('new pass'))
const f = JSON.parse(fs.readFileSync(file)); const b = Buffer.from(f.data, 'base64'); b[40] ^= 1
fs.writeFileSync(file, JSON.stringify({ ...f, data: b.toString('base64') })); v.lock()
assert.equal(v.unlock('new pass'), false, 'tampered vault must not open')
const g = generate(); assert(g.length === 20 && /[a-z]/.test(g) && /[A-Z]/.test(g) && /\d/.test(g))
const apple = 'Title,URL,Username,Password,Notes,OTPAuth\ngithub.com,https://github.com/,ali,"p,""q""\nline",my note,otpauth://totp/x\n'
const r = parseCsv(apple)
assert.deepEqual(r[0], { url: 'https://github.com/', username: 'ali', password: 'p,"q"\nline', title: 'github.com', notes: 'my note', otp: 'otpauth://totp/x' })
assert.equal(parseCsv('name,url,username,password,note\nX,https://a.com,u,p,\n')[0].password, 'p')
const round = parseCsv(toCsv([{ origin: 'https://github.com', username: 'ali', password: 'p,"q"\nline', notes: 'my note', otp: 'otpauth://totp/x', title: 'github.com' }]))
assert.equal(round[0].password, 'p,"q"\nline')
console.log('passwords: ok')
